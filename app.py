st.markdown(CSS, unsafe_allow_html=True)

SUGGESTIONS = [
    "Summarize this document",
    "What are the key points?",
    "List any important dates or deadlines",
]


@st.cache_resource(show_spinner="Loading the embedding model (first run takes a minute)...")
def get_embedder():
    return load_embedder()


embedder = get_embedder()

st.session_state.setdefault("sid", uuid.uuid4().hex[:12])
st.session_state.setdefault("messages", [])
st.session_state.setdefault("pending", None)
st.session_state.setdefault("flash", [])
st.session_state.setdefault("free_used", 0)
st.session_state.setdefault("user_key", "")

collection = get_collection(st.session_state.sid, public=PUBLIC)
docs = list_docs(collection)


def pick_key():
    """Return (api_key, kind). kind is 'own', 'free' or None."""
    own = st.session_state.user_key.strip()
    if own:
        return own, "own"
    server = os.getenv("GEMINI_API_KEY")
    if not PUBLIC:
        return server, "own"  # running on your own machine: use .env
    if server and st.session_state.free_used < FREE_QUESTIONS:
        return server, "free"
    return None, None


# ------------------------------------------------------------------ sidebar
with st.sidebar:
    st.markdown("## 🧠 VividMind")

    for kind, msg in st.session_state.flash:
        getattr(st, kind)(msg)
    st.session_state.flash = []

    if PUBLIC:
        st.caption(
            "🔒 Your PDFs live in memory for this session only and are deleted automatically. "
            "Answers are generated by Google Gemini, so don't upload confidential files."
        )
        st.text_input(
            "Your Gemini API key",
            type="password",
            key="user_key",
            placeholder="Paste a free key from aistudio.google.com",
            help="Used only for your questions in this session and never stored.",
        )
        left = max(0, FREE_QUESTIONS - st.session_state.free_used)
        if not st.session_state.user_key.strip() and os.getenv("GEMINI_API_KEY"):
            st.caption(f"Free demo questions left: **{left}**")

    files = st.file_uploader("Upload PDFs", type="pdf", accept_multiple_files=True)
    if st.button("⚡ Process PDFs", type="primary", use_container_width=True):
        if not files:
            st.warning("Choose at least one PDF first.")
        else:
            bar = st.progress(0.0, text="Indexing...")
            for i, f in enumerate(files, start=1):
                if f.size > MAX_UPLOAD_MB * 1024 * 1024:
                    st.session_state.flash.append(
                        ("warning", f"{f.name}: larger than {MAX_UPLOAD_MB} MB, skipped")
                    )
                elif PUBLIC and collection.count() >= MAX_CHUNKS:
                    st.session_state.flash.append(
                        ("warning", f"{f.name}: session limit reached, remove a document first")
                    )
                else:
                    try:
                        n = ingest_pdf(f.getvalue(), f.name, collection, embedder)
                    except Exception as e:
                        st.session_state.flash.append(("error", f"{f.name}: {e}"))
                    else:
                        if n:
                            st.session_state.flash.append(("success", f"{f.name}: {n} passages indexed"))
                        else:
                            st.session_state.flash.append(("warning", f"{f.name}: no text found (scanned PDF?)"))
                bar.progress(i / len(files), text=f"Processed {i}/{len(files)}")
            st.rerun()

    selected = []
    if docs:
        st.markdown("#### Library")
        for name, n in docs.items():
            c1, c2 = st.columns([5, 1])
            c1.markdown(f"📄 **{html.escape(name)}**  \n<small>{n} passages</small>", unsafe_allow_html=True)
            if c2.button("🗑", key=f"del_{name}", help="Remove this document"):
                delete_doc(collection, name)
                st.rerun()
        selected = st.multiselect("Search in", list(docs), default=list(docs))

    st.markdown("#### Settings")
    hybrid = st.toggle("Hybrid search (keywords + meaning)", value=True)
    k = st.slider("Passages to retrieve", 2, 8, 5)
    strict = st.slider(
        "Strictness", 0.0, 0.6, 0.1, 0.05,
        help="If the best passage matches less than this, VividMind says it can't find the answer instead of guessing.",
    )
    if st.button("Clear chat", use_container_width=True):
        st.session_state.messages = []
        st.rerun()

# --------------------------------------------------------------------- hero
total = sum(docs.values())
st.markdown(
    '<div class="vm-hero"><h1>VividMind</h1>'
    "<p>Chat with your documents. Every answer is grounded in the source and cited by page.</p></div>",
    unsafe_allow_html=True,
)
st.markdown(
    f'<div class="vm-stats">'
    f'<div class="vm-stat"><b>{len(docs)}</b><span>Documents</span></div>'
    f'<div class="vm-stat"><b>{total}</b><span>Passages indexed</span></div>'
    f'<div class="vm-stat"><b>{"Hybrid" if hybrid else "Vector"}</b><span>Search mode</span></div>'
    f"</div>",
    unsafe_allow_html=True,
)

if not docs:
    st.markdown(
        '<div class="vm-steps">'
        '<div class="vm-step"><div class="n">1</div><h4>Upload</h4><p>Add one or more PDFs in the sidebar.</p></div>'
        '<div class="vm-step"><div class="n">2</div><h4>Process</h4><p>VividMind splits them into passages and indexes them.</p></div>'
        '<div class="vm-step"><div class="n">3</div><h4>Ask</h4><p>Get answers with page citations and match scores.</p></div>'
        "</div>",
        unsafe_allow_html=True,
    )
    st.stop()


# ------------------------------------------------------------------ helpers
def render_sources(hits, mode, ms):
    with st.expander(f"📚 {len(hits)} sources · {mode} search · retrieved in {ms} ms"):
        for h in hits:
            snippet = html.escape(h["text"][:450])
            if h.get("overview"):
                score_html, bar_html = "sampled for overview", ""
            else:
                pct = max(0, min(100, int(h["similarity"] * 100)))
                score_html = f"{pct}% match"
                bar_html = f'<div class="vm-bar"><div style="width:{pct}%"></div></div>'
            st.markdown(
                f'<div class="vm-card"><div class="vm-head">'
                f'<span class="vm-chip">📄 {html.escape(h["file"])}</span>'
                f'<span class="vm-chip b">page {h["page"]}</span>'
                f'<span class="vm-score">{score_html}</span></div>'
                f'{bar_html}'
                f'<div class="vm-text">{snippet}…</div></div>',
                unsafe_allow_html=True,
            )


# --------------------------------------------------------------------- chat
for m in st.session_state.messages:
    with st.chat_message(m["role"]):
        st.markdown(m["content"])
        if m.get("sources"):
            render_sources(m["sources"], m["mode"], m["ms"])

if not st.session_state.messages:
    st.markdown("**Try asking**")
    cols = st.columns(len(SUGGESTIONS))
    for col, q in zip(cols, SUGGESTIONS):
        if col.button(q, use_container_width=True):
            st.session_state.pending = q
            st.rerun()

prompt = st.chat_input("Ask anything about your documents…")
if st.session_state.pending:
    prompt, st.session_state.pending = st.session_state.pending, None

if prompt:
    if not selected:
        st.warning("Select at least one document under 'Search in'.")
        st.stop()

    history = list(st.session_state.messages)
    st.session_state.messages.append({"role": "user", "content": prompt})
    with st.chat_message("user"):
        st.markdown(prompt)

    overview = is_overview_question(prompt)
    mode = "overview" if overview else ("hybrid" if hybrid else "vector")
    sources, ms = [], 0
    with st.chat_message("assistant"):
        t0 = time.perf_counter()
        if overview:
            hits = overview_passages(collection, selected)
        else:
            hits = retrieve(prompt, collection, embedder, k=k, files=selected, hybrid=hybrid)
        ms = int((time.perf_counter() - t0) * 1000)
        best = max((h["similarity"] for h in hits), default=0.0)

        if not hits or (not overview and best < strict):
            reply = NOT_FOUND
            st.markdown(reply)
            st.caption(f"Closest passage matched {int(best * 100)}%, below your strictness setting ({int(strict * 100)}%).")
        else:
            key, key_kind = pick_key()
            if PUBLIC and key is None:
                reply = (
                    "🔑 The free demo questions are used up. Paste your own free Gemini API key "
                    "in the sidebar (get one at aistudio.google.com) to keep chatting."
                )
                st.markdown(reply)
            else:
                if key_kind == "free":
                    st.session_state.free_used += 1
                reply = st.write_stream(stream_answer(prompt, hits, history, api_key=key))
                sources = [] if reply.strip().startswith("I couldn't find") else hits
                if sources:
                    render_sources(sources, mode, ms)

    st.session_state.messages.append(
        {"role": "assistant", "content": reply, "sources": sources, "mode": mode, "ms": ms}
    )
